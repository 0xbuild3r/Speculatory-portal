/**
 * Generate src/data.js from what actually exists (same rule as the console's generator):
 *   - ABIs come from Speculatory-contracts/out (compiled truth)
 *   - addresses come from Speculatory-backend/deployments/demo.json (the seeded demo state)
 * Rerun after any redeploy:  node scripts/build-data.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = resolve(root, '..', 'Speculatory-contracts', 'out');
const demo = resolve(root, '..', 'Speculatory-backend', 'deployments', 'demo.json');

// only what the author's screens read, write or decode from receipts
const NAMED = [
  'ThesisSpecRegistry', 'ThesisReview', 'ThesisFactory', 'ThesisVault', 'UnitToken', 'PolicyRegistry',
  'AccessController', 'AssetRegistry', 'IntentBook', 'SwapJournal', 'MarkJournal',
  'MockUSDC', 'MockChainlink', 'ERC20', 'ProtocolParams', 'FalsifierOracle', 'ConvictionStake',
];
const abis = {};
for (const name of NAMED) abis[name] = JSON.parse(readFileSync(resolve(outDir, name + '.sol', name + '.json'), 'utf8')).abi;

const manifest = JSON.parse(readFileSync(demo, 'utf8'));
const addrKeys = Object.keys(manifest).filter((k) => typeof manifest[k] === 'string' && manifest[k].startsWith('0x') && manifest[k].length === 42);
const addresses = Object.fromEntries(addrKeys.map((k) => [k, manifest[k]]));
if (manifest.chainId) addresses.chainId = manifest.chainId;

writeFileSync(resolve(root, 'src', 'data.js'), `// GENERATED by scripts/build-data.mjs — do not hand-edit.
// ABIs mirror the compiled contracts; addresses mirror the demo manifest.
export const ABI = ${JSON.stringify(abis)};
export const ADDRESS = ${JSON.stringify(addresses, null, 2)};
`);
console.log(`data.js: ${Object.keys(abis).length} contracts, ${addrKeys.length} addresses`);
